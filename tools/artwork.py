# Store icon, 512x512, rounded like a launcher icon.
(out / "icon.svg").write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">{defs}
<rect width="512" height="512" rx="112" fill="url(#bg)"/>
{svg_group(fg, "translate(-25.6,-25.6) scale(5.2)")}
</svg>''')


def confetti(w, h, seed):
    import random
    rnd = random.Random(seed)
    colors = SPRINKLES + ["#FFFFFF"]
    parts = []
    for _ in range(46):
        x, y = rnd.uniform(0, w), rnd.uniform(0, h)
        c, o = rnd.choice(colors), rnd.uniform(0.25, 0.7)
        if rnd.random() < 0.5:
            parts.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{rnd.uniform(3, 7):.1f}" fill="{c}" opacity="{o:.2f}"/>')
        else:
            parts.append(f'<rect x="{x:.0f}" y="{y:.0f}" width="{rnd.uniform(10, 20):.0f}" height="6" rx="3" fill="{c}" '
                         f'opacity="{o:.2f}" transform="rotate({rnd.uniform(0, 180):.0f} {x:.0f} {y:.0f})"/>')
    return "".join(parts)


def banner(w, h, title_size, tag_size):
    tile = h * 0.62
    tx, ty = w * 0.09, (h - tile) / 2
    scale = tile / 108 * 1.35
    cx, cy = tx + tile / 2 - 54 * scale, ty + tile / 2 - 51 * scale
    text_x = tx + tile + w * 0.06
    font = "Inter, 'Segoe UI', Roboto, 'Noto Sans', 'Helvetica Neue', Arial, sans-serif"
    pills = ["Open source", "No tracking", "SMS + Signal"]
    pill_y = h / 2 + tag_size * 2.3
    pill_svg, px = "", text_x
    for label in pills:
        pw = len(label) * tag_size * 0.38 + tag_size * 1.3
        pill_svg += (f'<rect x="{px:.0f}" y="{pill_y:.0f}" width="{pw:.0f}" height="{tag_size * 1.9:.0f}" '
                     f'rx="{tag_size * 0.95:.0f}" fill="#FFFFFF" fill-opacity="0.18" stroke="#FFFFFF" stroke-opacity="0.35"/>'
                     f'<text x="{px + pw / 2:.0f}" y="{pill_y + tag_size * 1.18:.0f}" text-anchor="middle" '
                     f'font-size="{tag_size * 0.66:.0f}" font-weight="600" fill="#FFFFFF">{label}</text>')
        px += pw + tag_size * 0.45
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">{defs}
<rect width="{w}" height="{h}" fill="url(#bg)"/>
{confetti(w, h, 7)}
<rect x="{tx:.0f}" y="{ty:.0f}" width="{tile:.0f}" height="{tile:.0f}" rx="{tile * 0.24:.0f}" fill="#FFFFFF" fill-opacity="0.16" stroke="#FFFFFF" stroke-opacity="0.3" stroke-width="2" filter="url(#soft)"/>
{svg_group(fg, f"translate({cx:.1f},{cy:.1f}) scale({scale:.3f})")}
<g font-family="{font}">
  <text x="{text_x:.0f}" y="{h / 2 - tag_size * 0.4:.0f}" font-size="{title_size}" font-weight="800" fill="#FFFFFF" letter-spacing="-1">Wishday</text>
  <text x="{text_x:.0f}" y="{h / 2 + tag_size * 1.3:.0f}" font-size="{tag_size}" font-weight="500" fill="#FFFFFF" fill-opacity="0.92">Never miss a birthday again.</text>
  {pill_svg}
</g>
</svg>'''


(out / "banner.svg").write_text(banner(1280, 640, 120, 34))
(out / "featureGraphic.svg").write_text(banner(1024, 500, 96, 27))
